import { test } from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import Stripe from 'stripe';
import { Billing } from '../src/billing.js';
import { fixture, listen, close } from './helpers.js';
import { quota } from '../src/config.js';

test('Stripe SDK checkout, signed webhooks, deduplication, current-state ordering and safe cancellation', async t => {
  const f = await fixture(); t.after(f.cleanup);
  await f.signUp('billing@example.test');
  const user = f.store.users()[0]; assert.ok(user);
  let status = 'active';
  let price = 'price_basic';
  let failed = false;
  let retrieves = 0;
  const api = express();
  api.use(express.urlencoded({ extended: true }));
  api.get('/v1/subscriptions/sub_one', (_req, res) => {
    retrieves++;
    if (failed) return res.status(503).json({ error: { type: 'api_error', message: 'synthetic failure' } });
    res.json({ id: 'sub_one', object: 'subscription', customer: 'cus_one', status, metadata: { sphotoUserId: user.id }, items: { data: [{ quantity: 1, price: { id: price, currency: 'chf', unit_amount: price === 'price_basic' ? 500 : 1500, recurring: { interval: 'month', interval_count: 1 } } }] } });
  });
  api.get('/v1/checkout/sessions/cs_one', (_req, res) => res.json({ id: 'cs_one', status: 'open', url: 'https://checkout.stripe.test/synthetic' }));
  api.post('/v1/checkout/sessions', (req, res) => {
    assert.equal(req.body.client_reference_id, user.id);
    assert.equal(req.body.line_items[0].price, 'price_basic');
    assert.equal(req.body.subscription_data.metadata.sphotoUserId, user.id);
    res.json({ id: 'cs_one', object: 'checkout.session', url: 'https://checkout.stripe.test/synthetic' });
  });
  const remote = await listen(api); t.after(() => close(remote.server));
  const url = new URL(remote.url);
  const client = new Stripe('sk_test_synthetic', { host: url.hostname, port: Number(url.port), protocol: 'http', maxNetworkRetries: 0 });
  const cfg = { ...f.cfg, BILLING_MODE: 'stripe', STRIPE_SECRET_KEY: 'sk_test_synthetic', STRIPE_WEBHOOK_SECRET: 'whsec_synthetic', STRIPE_PRICE_BASIC: 'price_basic', STRIPE_PRICE_PRO: 'price_pro' } satisfies typeof f.cfg;
  const billing = new Billing(cfg, f.store, f.immich, client);
  assert.equal(await billing.checkout(user, 'basic'), 'https://checkout.stripe.test/synthetic');
  assert.equal(await billing.checkout(user, 'pro'), 'https://checkout.stripe.test/synthetic');
  const send = async (id: string, type = 'customer.subscription.updated') => {
    const body = JSON.stringify({ id, object: 'event', type, data: { object: type === 'checkout.session.completed' ? { subscription: 'sub_one' } : { id: 'sub_one' } } });
    const signature = client.webhooks.generateTestHeaderString({ payload: body, secret: cfg.STRIPE_WEBHOOK_SECRET });
    await billing.webhook(Buffer.from(body), signature);
  };
  await assert.rejects(billing.webhook(Buffer.from('{}'), 'invalid'), /Invalid webhook signature/);
  assert.equal(f.store.user(user.id)?.plan, 'free');
  await send('evt_paid', 'checkout.session.completed');
  assert.equal(f.store.user(user.id)?.plan, 'basic');
  assert.equal(f.accounts.get(user.id)?.quotaSizeInBytes, quota('basic'));
  const before = retrieves;
  await send('evt_paid', 'checkout.session.completed');
  assert.equal(retrieves, before);
  const subscribed = f.store.user(user.id); assert.ok(subscribed);
  await assert.rejects(billing.checkout(subscribed, 'pro'), /Manage billing/);
  await assert.rejects(billing.manualPlan(user.id, 'pro'), /managed by Stripe/);
  price = 'price_pro';
  await send('evt_upgrade');
  assert.equal(f.store.user(user.id)?.plan, 'pro');
  await send('evt_delayed_old_update');
  assert.equal(f.store.user(user.id)?.plan, 'pro');
  failed = true;
  await assert.rejects(send('evt_retry'));
  assert.equal(f.store.seenEvent('evt_retry'), false);
  failed = false;
  await send('evt_retry');
  assert.equal(f.store.seenEvent('evt_retry'), true);
  const remoteUser = f.accounts.get(user.id); assert.ok(remoteUser); remoteUser.quotaUsageInBytes = quota('basic');
  status = 'canceled';
  await send('evt_cancel', 'customer.subscription.deleted');
  assert.equal(f.store.user(user.id)?.plan, 'free');
  assert.equal(f.accounts.get(user.id)?.quotaSizeInBytes, quota('free'));
  assert.equal(remoteUser.quotaUsageInBytes, quota('basic'));
  assert.equal(f.store.user(user.id)?.subscription, null);
  assert.equal(f.store.checkout(user.id), undefined);
  const canceled = f.store.user(user.id); assert.ok(canceled);
  assert.equal(await billing.checkout(canceled, 'basic'), 'https://checkout.stripe.test/synthetic');
});
